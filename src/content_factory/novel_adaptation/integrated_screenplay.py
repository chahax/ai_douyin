def choices():
    return [{'scope': '第21章末尾便利店的本次制作地点',
             'choice': '可沿用用户已接受的“融创乐园附近便利店”处理；不改成商场附近。',
             'provenance': '用户已接受当前候选地点；不是原文明确方位，也不推广为其他地理关系许可。'}]


def writer_payload(packet):
    return {'source': packet, 'production_choices': choices()}


def review_payload(packet, candidate):
    return {**writer_payload(packet), 'candidate': candidate}


def validate_result(value):
    errors = c.schema_issues(value, c.obj(text=c.TEXT), 'integrated_screenplay')
    if errors:
        raise c.ContractError(errors)
    if not value['text'].strip():
        raise ValueError('empty_screenplay')
    return {'protocol_passed': True, 'semantic_accepted': False,
            'characters': len(value['text']), 'requires_full_source_review': True}
