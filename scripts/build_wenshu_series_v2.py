def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    catalog = {
        "series_title": "证据怎么说",
        "visual_style": "现实主义律师圆桌研讨；冷静克制；固定三人身份；竖屏9:16；无宣传式镜头",
        "hand_policy": {
            "principle": "保留真实手部物品交互，但每个镜头只执行一次小幅、可验证接触动作",
            "safe_actions": ["预握文件夹后打开半程", "食指轻点固定证据卡", "双手分开做一次对比手势", "将刚性文件夹平移三厘米"],
            "avoid": ["薄纸高速运输", "交叉手臂取物", "一镜内连续抓取多个物体", "接触区使用光流插帧"],
            "qa": ["恰好两只手", "五指拓扑连续", "物体轮廓连续", "接触前后位置守恒", "无第三只手与融合指"],
        },
        "episodes": EPISODES,
    }
    (OUT / "series_catalog.json").write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    voice_lines = []
    for ep in EPISODES:
        for line in ep["lines"]:
            voice_lines.append({
                "id": line["id"],
                "scene_id": ep["episode_id"],
                "speaker": line["speaker"],
                "text": line["text"],
                "speed": 1.10,
                "instruct": line["performance"] + "。声音真实、有呼吸感，避免播音腔、广告腔和机械匀速。",
            })
    voice_spec = {
        "output_dir": str((OUT / "audio_cosyvoice").relative_to(ROOT)),
        "cast": CAST,
        "lines": voice_lines,
    }
    (OUT / "voice_spec.json").write_text(json.dumps(voice_spec, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    lines = [
        "# 《证据怎么说》10集律师圆桌系列",
        "",
        "- 每集约45—60秒，三人真实对话，无旁白、无硬性宣传。",
        "- 画面保持原版三位律师身份和会议室；每集6句，正反观点与证据方案闭环。",
        "- 法律结论以最高人民法院公开规则为内容边界，正式发布前仍需执业律师复核个案表述。",
        "- 手部动作保留，按预握、单次小幅接触、停稳三阶段生成；接触帧不做光流插帧。",
        "",
    ]
    for ep in EPISODES:
        lines.extend([f"## {ep['episode_id']} {ep['title']}", ""])
        lines.extend([f"{i}. **{row['speaker']}**：{row['text']}" for i, row in enumerate(ep["lines"], 1)])
        lines.extend(["", "依据：" + "；".join(item["url"] for item in ep["source_urls"]), ""])
    (OUT / "series_plan.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUT / "series_catalog.json")
    print(OUT / "voice_spec.json")
    print(OUT / "series_plan.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
